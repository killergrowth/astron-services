'use strict';
const fs = require('fs');
const path = require('path');
const { DIST } = require('./shared');

// Confirmed 2026-10-21 by Tyler B — redirect map from the legacy
// WordPress site (astronservicesks.com) to the new PKG002 build.
// Do not remove existing rows without checking with Tyler N/Tyler B first —
// these protect ranking/backlink equity from the old site.
const REDIRECTS = [
  ['/', '/'],
  ['/about-hvac-experts-in-wichita-ks/', '/about/'],
  ['/plumbing-service/', '/services/'],
  ['/hvac-contact-wichita/', '/contact/'],
  ['/request-service/', '/contact/'],
  ['/hvac-services-in-wichita-astron-services/', '/services/'],
  ['/hvac-repair-installation-wichita/', '/services/'],
  ['/indoor-air-quality-solutions-in-wichita/', '/indoor-air-quality/'],
  ['/hvac-reviews-in-wichita/', '/'],
  ['/home-services-tips-in-wichita/', '/blog/'],
  ['/thinking-about-getting-new-sink-faucets/', '/blog/'],
  ['/why-astron-services-was-started/', '/about/'],
];

function buildRedirects() {
  // Skip the root '/' -> '/' no-op row (not a real redirect, avoid a loop rule)
  const lines = REDIRECTS
    .filter(([from, to]) => from !== to)
    .map(([from, to]) => `${from}  ${to}  301`);

  const content = [
    '# Astron Services — legacy WordPress URL redirects',
    '# Generated by lib/build-redirects.js — confirmed map 2026-10-21',
    '# Do not hand-edit dist/_redirects; edit lib/build-redirects.js and rebuild.',
    '',
    ...lines,
    '',
  ].join('\n');

  fs.writeFileSync(path.join(DIST, '_redirects'), content, 'utf8');
  console.log(`Redirects written: ${lines.length} rules -> dist/_redirects`);
}

module.exports = { buildRedirects, REDIRECTS };
